// Token Radar — the value model (radar-2).
//
// One sealed snapshot of the protocol universe in, one ranked board out.
// The board ranks pre-token protocols by an implied launch value that is
// derived from the snapshot's own market figures, never from a list of
// names: every protocol is scored by the same function.
//
//   category multiple = the median market-cap / TVL of the token-bearing
//     protocols in the same category (at least 3 of them, else the
//     market-wide median), clamped to [0.05, 2.0]
//   base              = tvl_usd x category multiple
//   growth            = clamp(change_7d, -50, 100) per cent
//   growth multiplier = 1 + (growth / 100) x 0.6
//   maturity          = 0.7 + min(age_days, 1460) / 1460 x 0.5
//                       (age_days unknown: 365)
//   implied           = max(1, round(base x growth multiplier x maturity))
//
// A protocol is rankable when it records no token and is not a wrapped,
// staked or bridged product of a token that already trades — the same
// exclusion the snapshot's watchlist rule applies, extended to every
// board row. The watchlist is the floor: all 40 of its slugs are ranked,
// plus every rankable pre-token protocol below the floor.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

